import type { Insights, InsightItem } from '../analysis/insights';
import type { GapVerification } from '../analysis/verification';
import { Section, ShowMore, VerdictBadge } from './ui';

interface Props {
  insights: Insights;
  verifications: Record<string, GapVerification>;
  onItem: (t: InsightItem['target']) => void;
}

const SECTIONS: { key: keyof Insights; title: string; hint: string; empty: string; open: boolean }[] = [
  { key: 'themes', title: 'Common themes', hint: 'Behaviors and concepts discussed by 3 or more papers.', empty: 'No concept is shared by 3+ papers.', open: true },
  { key: 'methods', title: 'Shared methods', hint: 'Methods and evaluations used by 2 or more papers.', empty: 'No method is shared by 2+ papers.', open: true },
  { key: 'conflicts', title: 'Possibly conflicting claims', hint: 'Opposite claims about the same relationship. Check the review verdict: a different setting often explains them.', empty: 'No conflicting claim pairs detected.', open: false },
  { key: 'underexplored', title: 'Underexplored areas', hint: 'Top graph gaps that the AI-assisted review did not dismiss. Leads to check, not established research gaps.', empty: 'No gaps detected.', open: false },
  { key: 'directions', title: 'Suggested directions', hint: 'Generated by pairing an open gap with an observed result elsewhere in the collection that might address it. These are suggestions, not findings.', empty: 'No suggestion based on the collection.', open: false },
];

/** "Discover" tab: corpus-level patterns computed from the graph. Each item opens in the graph. */
export default function InsightsPanel({ insights, verifications, onItem }: Props) {
  return (
    <div className="tabpanel">
      <p className="intro">Patterns across the whole collection, computed from the graph. Select any item to see it in the graph.</p>
      {SECTIONS.map((s) => {
        const items = insights[s.key];
        return (
          <Section key={s.key} title={s.title} hint={s.hint} count={items.length} defaultOpen={s.open}>
            {items.length === 0 ? (
              <p className="muted small">{s.empty}</p>
            ) : (
              <ShowMore
                items={items}
                initial={4}
                className={`cards ${s.key === 'directions' ? 'suggested' : ''}`}
                render={(it, i) => {
                  const v = it.target.kind === 'gap' ? verifications[it.target.id] : undefined;
                  return (
                    <li key={i}>
                      <button className="card" onClick={() => onItem(it.target)}>
                        <span className="ctext">{it.text}</span>
                        <span className="cmeta">
                          <span className="refs">{it.refs}</span>
                          {it.target.kind === 'gap' && <VerdictBadge verdict={v?.verdict} />}
                        </span>
                      </button>
                    </li>
                  );
                }}
              />
            )}
          </Section>
        );
      })}
    </div>
  );
}
