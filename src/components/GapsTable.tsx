import { useState } from 'react';
import type { Gap, GapKind } from '../analysis/gaps';
import { GAP_KIND_LABEL } from '../analysis/gaps';
import type { GapVerification, Verdict } from '../analysis/verification';
import { VERDICT_LABEL } from '../analysis/verification';

interface Props {
  gaps: Gap[];
  verifications: Record<string, GapVerification>;
  onOpen: (gapId: string) => void;
}

export default function GapsTable({ gaps, verifications, onOpen }: Props) {
  const [kind, setKind] = useState<GapKind | 'all'>('all');
  const [verdict, setVerdict] = useState<Verdict | 'all' | 'unverified'>('all');
  const rows = gaps.filter(
    (g) =>
      (kind === 'all' || g.kind === kind) &&
      (verdict === 'all' || (verdict === 'unverified' ? !verifications[g.id] : verifications[g.id]?.verdict === verdict)),
  );
  return (
    <section className="panel gaps">
      <div className="panel-head">
        <h2>Knowledge gaps</h2>
        <span className="muted small">{rows.length} of {gaps.length} · generated by src/analysis/gaps.ts, resolutions limited to the uploaded corpus</span>
        <span className="spacer" />
        <select value={kind} onChange={(e) => setKind(e.target.value as GapKind | 'all')} aria-label="Gap type">
          <option value="all">All types</option>
          {Object.entries(GAP_KIND_LABEL).map(([k, v]) => <option key={k} value={k}>{v}</option>)}
        </select>
        <select value={verdict} onChange={(e) => setVerdict(e.target.value as Verdict | 'all' | 'unverified')} aria-label="Verdict">
          <option value="all">All verdicts</option>
          <option value="unverified">Not verified</option>
          {Object.entries(VERDICT_LABEL).map(([k, v]) => <option key={k} value={k}>{v}</option>)}
        </select>
      </div>
      <div className="tablewrap">
        <table>
          <thead>
            <tr><th>Gap</th><th>Type</th><th>Verdict</th><th className="num">Corpus fixes</th><th className="num">Score</th></tr>
          </thead>
          <tbody>
            {rows.map((g) => {
              const v = verifications[g.id];
              return (
                <tr key={g.id} onClick={() => onOpen(g.id)} tabIndex={0} onKeyDown={(e) => e.key === 'Enter' && onOpen(g.id)}>
                  <td>{g.title}{v && <div className="muted small">{v.note}</div>}</td>
                  <td><span className="badge">{GAP_KIND_LABEL[g.kind]}</span></td>
                  <td>{v ? <span className={`badge v-${v.verdict}`}>{VERDICT_LABEL[v.verdict]}</span> : <span className="muted small">—</span>}</td>
                  <td className="num">{g.resolutions.length}</td>
                  <td className="num">{g.score.toFixed(1)}</td>
                </tr>
              );
            })}
          </tbody>
        </table>
      </div>
    </section>
  );
}
